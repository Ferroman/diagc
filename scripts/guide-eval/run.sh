#!/usr/bin/env bash
# Cold-agent guide-coverage eval. One agent per case, cold (no skills, no context
# files, no session), allowed to read only `diagc guide all`; scored afterwards by
# assertions on the COMPILED artifact — never on the agent's own claims. Not a
# release gate: pass@1 depends on the model, so read it as a trend per release.
#
#   DIAGC_EVAL_AGENT='pi -p --model openai/chat-latest --no-skills --no-context-files --no-extensions --no-session --no-mcp' \
#     scripts/guide-eval/run.sh [case...]
#
# DIAGC_EVAL_AGENT is the command the brief is appended to, as its last argument.
# `diagc` must be on PATH (an installed release, to measure what ships). Cases are
# generated by mkcases.py into $DIAGC_EVAL_ROOT (default: <tmp>/diagc-guide-eval).
set -u
here=$(cd "$(dirname "$0")" && pwd)
root=${DIAGC_EVAL_ROOT:-${TMPDIR:-/tmp}/diagc-guide-eval}
agent=${DIAGC_EVAL_AGENT:?set DIAGC_EVAL_AGENT to the agent command the brief is passed to}
timeout_s=${DIAGC_EVAL_TIMEOUT:-480}
results=$root/results.txt

command -v diagc >/dev/null || { echo "diagc is not on PATH" >&2; exit 2; }
mkdir -p "$root"
diagc --version | sed 's/^/diagc /' | tee "$results"
echo "agent: $agent" | tee -a "$results"
diagc guide all > "$root/guide.md"
DIAGC_EVAL_ROOT=$root python3 "$here/mkcases.py" >/dev/null

cases=${*:-$(ls "$root/cases")}
for case in $cases; do
  d=$root/cases/$case
  name=$(DIAGC_EVAL_ROOT=$root python3 -c "import sys;sys.path.insert(0,'$here');from mkcases import CASES;print(CASES['$case']['name'])")
  echo "=== $case (diagram: $name) start $(date +%H:%M:%S)" | tee -a "$results"
  start=$(date +%s)
  ( cd "$d" && timeout "$timeout_s" $agent "$(cat TASK.md)" > "$d/agent.log" 2>"$d/agent.err" )
  rc=$?
  secs=$(( $(date +%s) - start ))
  iters=$(grep -o 'ITERATIONS: *[0-9]*' "$d/agent.log" | tail -1 | grep -o '[0-9]*')

  lint=$( cd "$d" && diagc lint --json 2>&1 ); lint_rc=$?
  # lint writes nothing: compile before scoring, or every case reports "no artifact"
  ( cd "$d" && diagc compile >/dev/null 2>&1 )
  art="$d/.diagrams/.artifacts/$name.diagram.json"
  [ -f "$art" ] || art=$(ls "$d"/.diagrams/.artifacts/*.diagram.json 2>/dev/null | head -1)
  if [ -n "${art:-}" ]; then
    verdict=$( cd "$d" && python3 checks.py "$art" 2>&1 )
  else
    verdict="FAIL  no artifact produced"
  fi
  { echo "  agent_rc=$rc  ${secs}s  lint_rc=$lint_rc  iterations=${iters:-?}"
    echo "  lint: $(echo "$lint" | head -c 220)"
    echo "$verdict" | sed 's/^/    /'
    echo "  artifact: ${art:-none}"
  } | tee -a "$results"
done
echo "=== done $(date +%H:%M:%S)" | tee -a "$results"
